

export function calculateDiscount(sum: number): number {
    if (sum <= 0) {
        throw new Error('нельзя передавать отрицательное число');
    }

    if (sum < 1000) {
        return sum;
    }

    return sum * 0.98;
}

// 1) при передаче 1 - результат должен быть 1
// 2) при передаче 999 - результат должен быть 999
// 3) при передаче 1000 - результат должен быть 980
// 4) при передаче 2000 - результат должен быть 1960
